CREATE SEQUENCE IF NOT EXISTS REQUEST_SEQ
    START WITH 1
    INCREMENT BY 50;

CREATE SEQUENCE IF NOT EXISTS REQUEST_AUDIT_SEQ
    START WITH 1
    INCREMENT BY 50;

CREATE SEQUENCE IF NOT EXISTS PUBLICATION_SEQ
    START WITH 100000
    INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS REQUESTS (
    ID BIGINT NOT NULL,
    NAME VARCHAR(200) NOT NULL,
    CONTENT VARCHAR(4000) NOT NULL,
    STATE VARCHAR(20) NOT NULL,
    PUBLICATION_NUMBER BIGINT,
    TERMINATION_REASON VARCHAR(1000),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    VERSION BIGINT DEFAULT 0 NOT NULL,

    CONSTRAINT PK_REQUESTS
        PRIMARY KEY (ID),

    CONSTRAINT UK_REQUESTS_PUBLICATION_NUMBER
        UNIQUE (PUBLICATION_NUMBER),

    CONSTRAINT CK_REQUESTS_STATE
        CHECK (
            STATE IN (
                'CREATED',
                'VERIFIED',
                'ACCEPTED',
                'PUBLISHED',
                'REJECTED',
                'DELETED'
            )
        )
);

CREATE TABLE IF NOT EXISTS REQUEST_AUDIT (
    ID BIGINT NOT NULL,
    REQUEST_ID BIGINT NOT NULL,
    FROM_STATE VARCHAR(20),
    TO_STATE VARCHAR(20),
    ACTION VARCHAR(50) NOT NULL,
    REASON VARCHAR(1000),
    ACTOR VARCHAR(255),
    OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT PK_REQUEST_AUDIT
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_AUDIT_REQUEST
        FOREIGN KEY (REQUEST_ID)
        REFERENCES REQUESTS(ID)
);

CREATE INDEX IF NOT EXISTS IX_REQUESTS_NAME
    ON REQUESTS (NAME);

CREATE INDEX IF NOT EXISTS IX_REQUESTS_CREATED_AT
    ON REQUESTS (CREATED_AT DESC);

CREATE INDEX IF NOT EXISTS IX_REQUESTS_STATE_CREATED_AT
    ON REQUESTS (STATE, CREATED_AT DESC);

CREATE INDEX IF NOT EXISTS IX_REQUEST_AUDIT_REQUEST_TIME
    ON REQUEST_AUDIT (REQUEST_ID, OCCURRED_AT DESC, ID);